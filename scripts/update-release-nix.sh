#!/usr/bin/env bash
# Point nix/release.json (packages.release, pkgs.contacts2mdsync-release) at a
# published GitHub release.
#
#   scripts/update-release-nix.sh <version>     # e.g. 0.2.0 (or v0.2.0)
#   scripts/update-release-nix.sh               # latest release (needs `gh`)
#
# Downloads https://github.com/zmre/contacts2mdsync/releases/download/v<version>/Contacts2MdSync-<version>.zip
# into the Nix store with `nix store prefetch-file`, records its SRI hash, and
# cross-checks it against the release's .sha256 asset when one exists.
# Review and commit the change to nix/release.json afterwards.
set -euo pipefail

readonly REPO="zmre/contacts2mdsync"
readonly APP_NAME="Contacts2MdSync"

die() {
  echo "error: $*" >&2
  exit 1
}

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
json="$root/nix/release.json"

version="${1:-}"
if [[ -z "$version" ]]; then
  command -v gh >/dev/null || die "no version given and gh is not installed; pass the version"
  version="$(gh release view --repo "$REPO" --json tagName --jq .tagName)"
fi
version="${version#v}"
[[ "$version" =~ ^[0-9]+\.[0-9]+(\.[0-9]+)?$ ]] || die "version '$version' must be X.Y or X.Y.Z"

url="https://github.com/$REPO/releases/download/v$version/$APP_NAME-$version.zip"
echo "prefetching $url"
prefetch="$(nix --extra-experimental-features 'nix-command flakes' \
  store prefetch-file --json --hash-type sha256 "$url")" ||
  die "download failed; is v$version published with $APP_NAME-$version.zip attached?"
hash="$(sed -n 's/.*"hash" *: *"\([^"]*\)".*/\1/p' <<<"$prefetch")"
[[ "$hash" == sha256-* ]] || die "could not read the hash from nix store prefetch-file"

# Cross-check with the published sha256 (hex) if the release has one.
if published="$(curl -fsSL "$url.sha256" 2>/dev/null)"; then
  published_hex="$(cut -d' ' -f1 <<<"$published")"
  ours_hex="$(nix --extra-experimental-features nix-command \
    hash convert --hash-algo sha256 --to base16 "$hash")"
  [[ "$published_hex" == "$ours_hex" ]] ||
    die "hash mismatch: release .sha256 says $published_hex, download is $ours_hex"
  echo "matches the published $APP_NAME-$version.zip.sha256"
else
  echo "warning: no $APP_NAME-$version.zip.sha256 asset; skipped cross-check" >&2
fi

cat >"$json" <<EOF
{
  "_comment": "Generated by scripts/update-release-nix.sh. The notarized GitHub release zip used by packages.release / pkgs.contacts2mdsync-release.",
  "version": "$version",
  "hash": "$hash"
}
EOF
echo "nix/release.json -> $version $hash"
echo "check: nix build path:.#release && codesign --verify --deep --strict result/Applications/$APP_NAME.app"
