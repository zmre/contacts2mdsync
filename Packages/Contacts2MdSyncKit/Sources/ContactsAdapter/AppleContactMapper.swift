public import ContactModel
public import Contacts
internal import Foundation

/// Maps a fetched `CNContact` to the canonical model.
///
/// Pure (no store access), so it is unit-tested with `CNMutableContact`s.
/// Every property read is guarded by `isKeyAvailable`: reading an unfetched
/// key raises an Objective-C exception, which would crash the process.
public enum AppleContactMapper {
    /// Keys fetched for every unified contact. `CNContactNoteKey` is added
    /// only when the notes entitlement was detected.
    public static func keysToFetch(includeNote: Bool) -> [any CNKeyDescriptor] {
        var keys: [String] = [
            CNContactIdentifierKey, CNContactTypeKey,
            CNContactNamePrefixKey, CNContactGivenNameKey, CNContactMiddleNameKey, CNContactFamilyNameKey,
            CNContactNameSuffixKey, CNContactNicknameKey, CNContactPreviousFamilyNameKey,
            CNContactOrganizationNameKey, CNContactDepartmentNameKey, CNContactJobTitleKey,
            CNContactPhoneticGivenNameKey, CNContactPhoneticMiddleNameKey, CNContactPhoneticFamilyNameKey,
            CNContactPhoneticOrganizationNameKey,
            CNContactEmailAddressesKey, CNContactPhoneNumbersKey, CNContactUrlAddressesKey,
            CNContactSocialProfilesKey, CNContactInstantMessageAddressesKey, CNContactPostalAddressesKey,
            CNContactBirthdayKey, CNContactDatesKey, CNContactRelationsKey,
            CNContactImageDataKey, CNContactImageDataAvailableKey, CNContactThumbnailImageDataKey,
        ]
        if includeNote { keys.append(CNContactNoteKey) }
        return keys.map { $0 as NSString }
    }

    /// Keys fetched for underlying cards: every field except images, so the
    /// engine can compute values by card precedence (architecture §6) instead
    /// of trusting the unified view's blend.
    public static func cardKeys(includeNote: Bool) -> [any CNKeyDescriptor] {
        let imageKeys: Set<String> = [
            CNContactImageDataKey, CNContactImageDataAvailableKey, CNContactThumbnailImageDataKey,
        ]
        return keysToFetch(includeNote: includeNote).filter { !imageKeys.contains(($0 as? String) ?? "") }
    }

    /// The canonical contact for `contact`. `title` is left empty (it is
    /// markdown-owned and generated by the planner); the `x-c2mdsync:` stamp is
    /// removed from `urls`.
    public static func canonical(from contact: CNContact) -> CanonicalContact {
        let has = { (key: String) in contact.isKeyAvailable(key) }
        let kind: ContactKind = has(CNContactTypeKey) && contact.contactType == .organization ? .organization : .person
        var result = CanonicalContact(kind: kind, title: "")
        mapNames(contact, into: &result)
        if has(CNContactEmailAddressesKey) {
            result.emails = contact.emailAddresses.compactMap { labeled($0.label, $0.value as String) }
        }
        if has(CNContactPhoneNumbersKey) {
            result.phones = contact.phoneNumbers.compactMap { labeled($0.label, $0.value.stringValue) }
        }
        if has(CNContactUrlAddressesKey) {
            result.urls = contact.urlAddresses.filter { !SyncStamp.isStamp($0.value as String) }
                .compactMap { labeled($0.label, $0.value as String) }
        }
        if has(CNContactSocialProfilesKey) { result.social = contact.socialProfiles.compactMap(social) }
        if has(CNContactInstantMessageAddressesKey) { result.im = contact.instantMessageAddresses.compactMap(im) }
        if has(CNContactPostalAddressesKey) { result.addresses = contact.postalAddresses.compactMap(address) }
        result.dates = dates(of: contact)
        if has(CNContactRelationsKey) { result.relationships = contact.contactRelations.compactMap(relation) }
        if has(CNContactNoteKey), let note = clean(contact.note) { result.body = note + "\n" }
        return result
    }

    /// Name parts, aliases, organization fields and phonetics.
    private static func mapNames(_ contact: CNContact, into result: inout CanonicalContact) {
        let text = { (key: String, value: () -> String) in contact.isKeyAvailable(key) ? clean(value()) : nil }
        result.name = PersonName(
            prefix: text(CNContactNamePrefixKey) { contact.namePrefix },
            given: text(CNContactGivenNameKey) { contact.givenName },
            middle: text(CNContactMiddleNameKey) { contact.middleName },
            family: text(CNContactFamilyNameKey) { contact.familyName },
            suffix: text(CNContactNameSuffixKey) { contact.nameSuffix }
        )
        result.aliases = [
            text(CNContactNicknameKey) { contact.nickname }.map(Alias.nickname),
            text(CNContactPreviousFamilyNameKey) { contact.previousFamilyName }.map(Alias.maidenName),
        ].compactMap { $0 }
        result.company = text(CNContactOrganizationNameKey) { contact.organizationName }.map(CompanyRef.plain)
        result.department = text(CNContactDepartmentNameKey) { contact.departmentName }
        result.jobTitle = text(CNContactJobTitleKey) { contact.jobTitle }
        result.apple = AppleExtras(
            phoneticGiven: text(CNContactPhoneticGivenNameKey) { contact.phoneticGivenName },
            phoneticMiddle: text(CNContactPhoneticMiddleNameKey) { contact.phoneticMiddleName },
            phoneticFamily: text(CNContactPhoneticFamilyNameKey) { contact.phoneticFamilyName },
            phoneticOrganization: text(CNContactPhoneticOrganizationNameKey) { contact.phoneticOrganizationName }
        )
    }

    /// The `x-c2mdsync:` stamp id on `contact`, if its URLs were fetched and carry one.
    public static func stampID(of contact: CNContact) -> UUID? {
        guard contact.isKeyAvailable(CNContactUrlAddressesKey) else { return nil }
        return contact.urlAddresses.lazy.compactMap { SyncStamp.id(fromURL: $0.value as String) }.first
    }

    /// `true` when Contacts reports no original image data but has a
    /// thumbnail (seen after an iCloud round trip, spike S5): image unknown.
    public static func imageUnavailable(of contact: CNContact) -> Bool {
        guard contact.isKeyAvailable(CNContactImageDataAvailableKey), !contact.imageDataAvailable,
            contact.isKeyAvailable(CNContactThumbnailImageDataKey)
        else { return false }
        return contact.thumbnailImageData?.isEmpty == false
    }

    /// Original image bytes, when fetched and present.
    public static func imageData(of contact: CNContact) -> Data? {
        guard contact.isKeyAvailable(CNContactImageDataAvailableKey), contact.imageDataAvailable,
            contact.isKeyAvailable(CNContactImageDataKey)
        else { return nil }
        return contact.imageData
    }

    // MARK: - Fields

    static func clean(_ text: String?) -> String? {
        guard let trimmed = text?.trimmingCharacters(in: .whitespacesAndNewlines), !trimmed.isEmpty else { return nil }
        return trimmed
    }

    private static func labeled(_ label: String?, _ value: String) -> Labeled<String>? {
        clean(value).map { Labeled(LabelMap.markdownLabel(fromApple: label), $0) }
    }

    static func social(_ entry: CNLabeledValue<CNSocialProfile>) -> Labeled<SocialHandle>? {
        let profile = entry.value
        let username = clean(profile.username)
        var url = clean(profile.urlString)
        if let candidate = url, let username,
            isSynthesizedProfileURL(candidate, service: profile.service, username: username)
        {
            url = nil
        }
        guard let value = url ?? username else { return nil }
        return Labeled(LabelMap.serviceLabel(service: profile.service, label: entry.label), SocialHandle(value))
    }

    /// Contacts fills in `urlString` for known services on save (spike S5:
    /// Twitter `zzspike` → `http://twitter.com/zzspike`). Such a URL is not
    /// exported, so a bare handle stays a bare handle (markdown-schema §2).
    static func isSynthesizedProfileURL(_ url: String, service: String?, username: String) -> Bool {
        let templates: [String: [String]] = [
            "twitter": ["http://twitter.com/%@", "http://www.twitter.com/%@", "http://x.com/%@"],
            "facebook": ["http://www.facebook.com/%@", "http://facebook.com/%@"],
            "flickr": ["http://www.flickr.com/photos/%@"],
            "linkedin": ["http://www.linkedin.com/in/%@"],
            "myspace": ["http://www.myspace.com/%@"],
            "sinaweibo": ["http://weibo.com/n/%@"],
        ]
        let key = (service ?? "").lowercased().replacingOccurrences(of: " ", with: "")
        let lowered = url.lowercased()
        return (templates[key] ?? []).contains {
            $0.replacingOccurrences(of: "%@", with: username.lowercased()) == lowered
        }
    }

    static func im(_ entry: CNLabeledValue<CNInstantMessageAddress>) -> Labeled<IMHandle>? {
        let address = entry.value
        guard let value = clean(address.username) else { return nil }
        return Labeled(LabelMap.serviceLabel(service: address.service, label: entry.label), IMHandle(value))
    }

    static func address(_ entry: CNLabeledValue<CNPostalAddress>) -> Labeled<PostalAddress>? {
        let postal = entry.value
        let address = PostalAddress(
            street: clean(postal.street),
            city: clean(postal.city),
            region: clean(postal.state),
            postcode: clean(postal.postalCode),
            country: clean(postal.country),
            countryCode: clean(postal.isoCountryCode)?.uppercased()
        )
        return address.isEmpty ? nil : Labeled(LabelMap.markdownLabel(fromApple: entry.label), address)
    }

    private static func dates(of contact: CNContact) -> [Labeled<PartialDate>] {
        var result: [Labeled<PartialDate>] = []
        if contact.isKeyAvailable(CNContactBirthdayKey), let birthday = contact.birthday,
            let date = partialDate(birthday)
        {
            result.append(Labeled("birthday", date))
        }
        if contact.isKeyAvailable(CNContactDatesKey) {
            for entry in contact.dates {
                guard let date = partialDate(entry.value as DateComponents) else { continue }
                // mbr needs a label on every date; unlabeled Apple dates become `other`.
                result.append(Labeled(LabelMap.markdownLabel(fromApple: entry.label) ?? "other", date))
            }
        }
        return result
    }

    /// `DateComponents` → `PartialDate`; `nil` without month and day.
    static func partialDate(_ components: DateComponents) -> PartialDate? {
        func defined(_ value: Int?) -> Int? {
            guard let value, value != NSDateComponentUndefined else { return nil }
            return value
        }
        guard let month = defined(components.month), let day = defined(components.day),
            (1...12).contains(month), (1...31).contains(day)
        else { return nil }
        if let year = defined(components.year) { return .full(year: year, month: month, day: day) }
        return .monthDay(month: month, day: day)
    }

    static func relation(_ entry: CNLabeledValue<CNContactRelation>) -> RelationshipRef? {
        guard let name = clean(entry.value.name) else { return nil }
        let mapped = RelationLabelMap.mbr(fromApple: entry.label)
        return RelationshipRef(type: mapped.type, label: mapped.label, target: .name(name))
    }
}
